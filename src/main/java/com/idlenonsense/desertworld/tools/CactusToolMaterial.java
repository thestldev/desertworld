package com.idlenonsense.desertworld.tools;

import com.idlenonsense.desertworld.item.ModItems;
import net.fabricmc.yarn.constants.MiningLevels;
import net.minecraft.item.Items;
import net.minecraft.item.ToolMaterial;
import net.minecraft.recipe.Ingredient;
import net.minecraft.util.Lazy;

import java.util.function.Supplier;

public enum CactusToolMaterial implements ToolMaterial {
    CACTUS(MiningLevels.STONE, 131, 4.0F, 1.0F, 5, () -> Ingredient.ofItems(Items.CACTUS)),
    SANDSTONE(MiningLevels.IRON, 212, 5.0F, 1.0F, 5, () -> Ingredient.ofItems(Items.SANDSTONE)),
    CURSED(MiningLevels.DIAMOND, 112, 6.0F, 1.0F, 5, () -> Ingredient.ofItems(ModItems.CURSED_GOLD));

    private final int miningLevel;
    private final int itemDurability;
    private final float miningSpeed;
    private final float attackDamage;
    private final int enchantability;
    private final Lazy<Ingredient> repairIngredient;

    private CactusToolMaterial(int miningLevel, int itemDurability, float miningSpeed, float attackDamage, int enchantability, Supplier<Ingredient> repairIngredient) {
        this.miningLevel = miningLevel;
        this.itemDurability = itemDurability;
        this.miningSpeed = miningSpeed;
        this.attackDamage = attackDamage;
        this.enchantability = enchantability;
        this.repairIngredient = new Lazy<>(repairIngredient);
    }

    @Override
    public int getDurability() {
        return this.itemDurability;
    }

    @Override
    public float getMiningSpeedMultiplier() {
        return this.miningSpeed;
    }

    @Override
    public float getAttackDamage() {
        return this.attackDamage;
    }

    @Override
    public int getMiningLevel() {
        return this.miningLevel;
    }

    @Override
    public int getEnchantability() {
        return this.enchantability;
    }

    @Override
    public Ingredient getRepairIngredient() {
        return this.repairIngredient.get();
    }
}
